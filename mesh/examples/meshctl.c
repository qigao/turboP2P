static void meshctl_build_vip_dht_key(char *buf, size_t buf_len) {
    snprintf(buf, buf_len, "mesh:%s:ip:%s", g_config.network_id, g_config.virtual_ip);
}

static int meshctl_build_reverse_dht_key(char *buf, size_t buf_len) {
    if (!g_config.advertise_ip[0]) {
        return 0;
    }

    snprintf(buf, buf_len, "mesh:%s:peer:%s:%d",
             g_config.network_id, g_config.advertise_ip, g_config.listen_port);
    return 1;
}

static void meshctl_build_routes_dht_key(char *buf, size_t buf_len) {
    snprintf(buf, buf_len, "mesh:%s:routes:%s",
             g_config.network_id, g_config.virtual_ip);
}

static void meshctl_print_dht_known_entry_json(mesh_network_t *mesh,
                                               const char *label,
                                               const char *key) {
    char value[1024] = {0};
    size_t value_len = sizeof(value);
    int found = 0;

    printf("{\"label\":");
    meshctl_print_json_string(label);
    printf(",\"key\":");
    meshctl_print_json_string(key ? key : "");

    if (key && mesh_get_cached_dht_value(mesh, key, value, &value_len) == MESH_OK) {
        found = 1;
    }

    printf(",\"present\":%s", found ? "true" : "false");
    printf(",\"value\":");
    meshctl_print_json_string(found ? value : "");
    printf("}");
}

static void meshctl_print_dht_json_fields(mesh_network_t *mesh) {
    mesh_stats_t stats;
    char vip_key[128];
    char reverse_key[128];
    char routes_key[128];
    int emitted = 0;

    if (mesh_get_stats(mesh, &stats) != MESH_OK) {
        fprintf(stderr, "Failed to read mesh stats\n");
        return;
    }

    meshctl_build_vip_dht_key(vip_key, sizeof(vip_key));
    meshctl_build_routes_dht_key(routes_key, sizeof(routes_key));

    printf("\"dht\":{\"entry_count\":%u,\"known_entries\":[", stats.dht_entries);
    meshctl_print_dht_known_entry_json(mesh, "virtual_ip", vip_key);
    emitted = 1;

    if (meshctl_build_reverse_dht_key(reverse_key, sizeof(reverse_key))) {
        if (emitted) {
            putchar(',');
        }
        meshctl_print_dht_known_entry_json(mesh, "reverse_peer", reverse_key);
        emitted = 1;
    }

    if (emitted) {
        putchar(',');
    }
    meshctl_print_dht_known_entry_json(mesh, "routes", routes_key);
    printf("]}");
}

static void meshctl_print_dht_json(mesh_network_t *mesh) {
    printf("{");
    meshctl_print_dht_json_fields(mesh);
    printf("}\n");
}

static void meshctl_print_dht(mesh_network_t *mesh) {
    mesh_stats_t stats;
    char vip_key[128];
    char reverse_key[128];
    char routes_key[128];
    char value[1024];
    size_t value_len = 0;

    if (mesh_get_stats(mesh, &stats) != MESH_OK) {
        fprintf(stderr, "Failed to read mesh stats\n");
        return;
    }

    printf("[dht] entries=%u\n", stats.dht_entries);

    meshctl_build_vip_dht_key(vip_key, sizeof(vip_key));
    value_len = sizeof(value);
    if (mesh_get_cached_dht_value(mesh, vip_key, value, &value_len) == MESH_OK) {
        printf("[dht] virtual_ip key=%s value=%s\n", vip_key, value);
    } else {
        printf("[dht] virtual_ip key=%s value=(missing)\n", vip_key);
    }

    if (meshctl_build_reverse_dht_key(reverse_key, sizeof(reverse_key))) {
        value_len = sizeof(value);
        if (mesh_get_cached_dht_value(mesh, reverse_key, value, &value_len) == MESH_OK) {
            printf("[dht] reverse_peer key=%s value=%s\n", reverse_key, value);
        } else {
            printf("[dht] reverse_peer key=%s value=(missing)\n", reverse_key);
        }
    }

    meshctl_build_routes_dht_key(routes_key, sizeof(routes_key));
    value_len = sizeof(value);
    if (mesh_get_cached_dht_value(mesh, routes_key, value, &value_len) == MESH_OK) {
        printf("[dht] routes key=%s value=%s\n", routes_key, value[0] ? value : "(empty)");
    } else {
        printf("[dht] routes key=%s value=(missing)\n", routes_key);
    }
}

