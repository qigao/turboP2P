static int meshctl_build_ping_packet(const char *src_ip,
                                     const char *dst_ip,
                                     uint8_t *packet,
                                     size_t packet_len,
                                     size_t *out_len,
                                     int is_reply,
                                     unsigned int seq,
                                     uint64_t sent_ms) {
    char payload[96];
    size_t payload_len = 0;
    uint32_t src = parse_ipv4_be(src_ip);
    uint32_t dst = parse_ipv4_be(dst_ip);

    payload_len = (size_t)snprintf(payload, sizeof(payload),
                                   "%s:%u:%llu",
                                   is_reply ? "meshctl-pong" : "meshctl-ping",
                                   seq,
                                   (unsigned long long)sent_ms);
    if (payload_len >= sizeof(payload)) {
        return -1;
    }

    {
        size_t total_len = 20 + payload_len;

        if (!src || !dst || !packet || !out_len || packet_len < total_len) {
            return -1;
        }

        memset(packet, 0, total_len);
        packet[0] = 0x45;
        packet[2] = (uint8_t)((total_len >> 8) & 0xffU);
        packet[3] = (uint8_t)(total_len & 0xffU);
        packet[8] = 64;
        packet[9] = 253; /* Experimental protocol, enough for mesh routing tests. */
        packet[12] = (uint8_t)((src >> 24) & 0xffU);
        packet[13] = (uint8_t)((src >> 16) & 0xffU);
        packet[14] = (uint8_t)((src >> 8) & 0xffU);
        packet[15] = (uint8_t)(src & 0xffU);
        packet[16] = (uint8_t)((dst >> 24) & 0xffU);
        packet[17] = (uint8_t)((dst >> 16) & 0xffU);
        packet[18] = (uint8_t)((dst >> 8) & 0xffU);
        packet[19] = (uint8_t)(dst & 0xffU);
        memcpy(packet + 20, payload, payload_len);
        *out_len = total_len;
    }
    return 0;
}

static int meshctl_pick_ping_target(mesh_network_t *mesh, char *target, size_t target_len) {
    mesh_peer_info_t info;

    if (mesh_get_peer_count(mesh) <= 0) {
        return -1;
    }

    if (mesh_get_peer_info(mesh, 0, &info) != MESH_OK || !info.is_connected) {
        return -1;
    }

    strncpy(target, info.virtual_ip, target_len - 1);
    target[target_len - 1] = '\0';
    return 0;
}

static void meshctl_send_ping(mesh_network_t *mesh, const char *target_ip) {
    uint8_t packet[128];
    size_t packet_len = 0;
    int ret = 0;
    unsigned int seq = 0;
    uint64_t now_ms = 0;

    if (!target_ip || !parse_ipv4(target_ip)) {
        fprintf(stderr, "Invalid ping target: %s\n", target_ip ? target_ip : "(null)");
        return;
    }

    seq = ++g_ping_seq;
    now_ms = meshctl_now_ms();

    if (meshctl_build_ping_packet(g_config.virtual_ip, target_ip, packet, sizeof(packet),
                                  &packet_len, 0, seq, now_ms) != 0) {
        fprintf(stderr, "Failed to build ping packet\n");
        return;
    }

    ret = mesh_send_packet(mesh, packet, packet_len);
    if (ret != MESH_OK) {
        fprintf(stderr, "Ping send failed: %s\n", mesh_error_string((mesh_error_t)ret));
        return;
    }

    g_last_ping_seq = seq;
    g_last_ping_sent_ms = now_ms;
    strncpy(g_last_ping_target, target_ip, sizeof(g_last_ping_target) - 1);
    g_last_ping_target[sizeof(g_last_ping_target) - 1] = '\0';

    printf("[ping] seq=%u sent %zu bytes from %s to %s\n",
           seq, packet_len, g_config.virtual_ip, target_ip);
}

static void meshctl_handle_command(mesh_network_t *mesh, char *command) {
    char *args = NULL;

    command = trim(command);
    if (*command == '\0') {
        return;
    }

    args = strchr(command, ' ');
    if (args) {
        *args = '\0';
        args = trim(args + 1);
    }

    if (strcmp(command, "status") == 0) {
        if (meshctl_args_want_json(args)) {
            meshctl_print_status_json(mesh);
        } else {
            meshctl_print_status(mesh);
        }
        return;
    }

    if (strcmp(command, "health") == 0) {
        if (meshctl_args_want_json(args)) {
            printf("{");
            meshctl_print_health_json_fields(mesh);
            printf("}\n");
        } else {
            meshctl_print_health(mesh);
        }
        return;
    }

    if (strcmp(command, "dht") == 0) {
        if (meshctl_args_want_json(args)) {
            meshctl_print_dht_json(mesh);
        } else {
            meshctl_print_dht(mesh);
        }
        return;
    }

    if (strcmp(command, "peers") == 0) {
        if (meshctl_args_want_json(args)) {
            meshctl_print_peers_json(mesh);
        } else {
            meshctl_print_peers(mesh);
        }
        return;
    }

    if (strcmp(command, "routes") == 0) {
        if (meshctl_args_want_json(args)) {
            meshctl_print_routes_json(mesh);
        } else {
            meshctl_print_routes(mesh);
        }
        return;
    }

    if (strcmp(command, "policy") == 0) {
        if (meshctl_args_want_json(args)) {
            meshctl_print_policy_json(mesh);
        } else {
            meshctl_print_policy(mesh);
        }
        return;
    }

    if (strcmp(command, "admission") == 0) {
        if (meshctl_args_want_json(args)) {
            meshctl_print_admission_json(mesh);
        } else {
            meshctl_print_admission(mesh);
        }
        return;
    }

    if (strcmp(command, "dump") == 0 || strcmp(command, "diag") == 0) {
        if (meshctl_args_want_json(args)) {
            meshctl_print_dump_json(mesh);
        } else {
            meshctl_print_dump(mesh);
        }
        return;
    }

    if (strcmp(command, "help") == 0) {
        meshctl_print_help();
        return;
    }

    if (strcmp(command, "quit") == 0 || strcmp(command, "exit") == 0) {
        g_running = 0;
        return;
    }

    if (strcmp(command, "ping") == 0) {
        char target[16] = {0};

        if (args && *args) {
            strncpy(target, args, sizeof(target) - 1);
        } else if (meshctl_pick_ping_target(mesh, target, sizeof(target)) != 0) {
            fprintf(stderr, "No connected peer available for ping\n");
            return;
        }

        meshctl_send_ping(mesh, target);
        return;
    }

    fprintf(stderr, "Unknown command: %s\n", command);
    meshctl_print_help();
}

static void meshctl_command_queue_init(meshctl_command_queue_t *queue) {
    memset(queue, 0, sizeof(*queue));
    turbo_mutex_init(&queue->mutex);
}

static void meshctl_command_queue_destroy(meshctl_command_queue_t *queue) {
    turbo_mutex_destroy(&queue->mutex);
}

static int meshctl_command_queue_push(meshctl_command_queue_t *queue, const char *command) {
    int accepted = 0;

    turbo_mutex_lock(&queue->mutex);
    if (queue->count < MESHCTL_COMMAND_QUEUE_SIZE && !queue->stop) {
        strncpy(queue->commands[queue->tail], command, MESHCTL_MAX_COMMAND - 1);
        queue->commands[queue->tail][MESHCTL_MAX_COMMAND - 1] = '\0';
        queue->tail = (queue->tail + 1) % MESHCTL_COMMAND_QUEUE_SIZE;
        queue->count++;
        accepted = 1;
    }
    turbo_mutex_unlock(&queue->mutex);
    return accepted;
}

static int meshctl_command_queue_pop(meshctl_command_queue_t *queue, char *command, size_t command_len) {
    int has_command = 0;

    turbo_mutex_lock(&queue->mutex);
    if (queue->count > 0) {
        strncpy(command, queue->commands[queue->head], command_len - 1);
        command[command_len - 1] = '\0';
        queue->commands[queue->head][0] = '\0';
        queue->head = (queue->head + 1) % MESHCTL_COMMAND_QUEUE_SIZE;
        queue->count--;
        has_command = 1;
    }
    turbo_mutex_unlock(&queue->mutex);
    return has_command;
}

static int meshctl_command_queue_has_pending(meshctl_command_queue_t *queue) {
    int has_pending = 0;

    turbo_mutex_lock(&queue->mutex);
    has_pending = queue->count > 0;
    turbo_mutex_unlock(&queue->mutex);
    return has_pending;
}

static void meshctl_command_queue_stop(meshctl_command_queue_t *queue) {
    turbo_mutex_lock(&queue->mutex);
    queue->stop = 1;
    turbo_mutex_unlock(&queue->mutex);
}

static void meshctl_stdin_thread(void *arg) {
    meshctl_command_queue_t *queue = (meshctl_command_queue_t *)arg;
    char line[MESHCTL_MAX_COMMAND];

    while (g_running) {
        if (!fgets(line, sizeof(line), stdin)) {
            meshctl_command_queue_stop(queue);
            g_running = 0;
            break;
        }

        line[strcspn(line, "\r\n")] = '\0';
        if (!meshctl_command_queue_push(queue, line)) {
            fprintf(stderr, "Command dropped, queue is full\n");
        }

        if (strcmp(line, "quit") == 0 || strcmp(line, "exit") == 0) {
            break;
        }
    }
}

