static void on_packet_received(const uint8_t *data, size_t len, void *user_data) {
    char src[16];
    char dst[16];
    char payload[64];
    char kind[16];
    size_t payload_len = 0;
    uint32_t src_ip = 0;
    uint32_t dst_ip = 0;
    unsigned int seq = 0;
    unsigned long long sent_ms = 0;
    uint8_t reply[128];
    size_t reply_len = 0;
    int send_ret = 0;
    uint64_t now_ms = meshctl_now_ms();

    (void)user_data;

    if (!data || len < 20) {
        printf("[packet] received short packet: %zu bytes\n", len);
        return;
    }

    src_ip = ((uint32_t)data[12] << 24) |
             ((uint32_t)data[13] << 16) |
             ((uint32_t)data[14] << 8) |
             (uint32_t)data[15];
    dst_ip = ((uint32_t)data[16] << 24) |
             ((uint32_t)data[17] << 16) |
             ((uint32_t)data[18] << 8) |
             (uint32_t)data[19];

    format_ipv4_be(src_ip, src, sizeof(src));
    format_ipv4_be(dst_ip, dst, sizeof(dst));

    payload_len = len > 20 ? len - 20 : 0;
    if (payload_len >= sizeof(payload)) {
        payload_len = sizeof(payload) - 1;
    }

    if (payload_len > 0) {
        memcpy(payload, data + 20, payload_len);
    }
    payload[payload_len] = '\0';

    if (sscanf(payload, "%15[^:]:%u:%llu", kind, &seq, &sent_ms) == 3) {
        if (strcmp(kind, "meshctl-ping") == 0) {
            printf("[ping] request seq=%u %s -> %s\n", seq, src, dst);

            if (meshctl_build_ping_packet(g_config.virtual_ip, src, reply, sizeof(reply),
                                          &reply_len, 1, seq, (uint64_t)sent_ms) == 0) {
                send_ret = mesh_send_packet(g_mesh, reply, reply_len);
                if (send_ret == MESH_OK) {
                    printf("[ping] reply seq=%u %s -> %s\n", seq, g_config.virtual_ip, src);
                } else {
                    fprintf(stderr, "Failed to send ping reply: %s\n",
                            mesh_error_string((mesh_error_t)send_ret));
                }
            }
            return;
        }

        if (strcmp(kind, "meshctl-pong") == 0) {
            printf("[ping] reply seq=%u from %s rtt=%llums\n",
                   seq, src, (unsigned long long)(now_ms - (uint64_t)sent_ms));
            return;
        }
    }

    printf("[packet] proto=%u %s -> %s payload=\"%s\"\n", (unsigned)data[9], src, dst, payload);
}

