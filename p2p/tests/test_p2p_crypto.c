#include "crypto/p2p_crypto.h"

#include <stdio.h>
#include <string.h>

static int bytes_equal(const uint8_t *a, const uint8_t *b, size_t size) {
  return size == 0u || memcmp(a, b, size) == 0;
}

int main(void) {
  static const uint8_t sha256_empty[32] = {
      0xe3,0xb0,0xc4,0x42,0x98,0xfc,0x1c,0x14,
      0x9a,0xfb,0xf4,0xc8,0x99,0x6f,0xb9,0x24,
      0x27,0xae,0x41,0xe4,0x64,0x9b,0x93,0x4c,
      0xa4,0x95,0x99,0x1b,0x78,0x52,0xb8,0x55};
  static const uint8_t sha256_abc[32] = {
      0xba,0x78,0x16,0xbf,0x8f,0x01,0xcf,0xea,
      0x41,0x41,0x40,0xde,0x5d,0xae,0x22,0x23,
      0xb0,0x03,0x61,0xa3,0x96,0x17,0x7a,0x9c,
      0xb4,0x10,0xff,0x61,0xf2,0x00,0x15,0xad};
  static const uint8_t hmac_expected[32] = {
      0xb0,0x34,0x4c,0x61,0xd8,0xdb,0x38,0x53,
      0x5c,0xa8,0xaf,0xce,0xaf,0x0b,0xf1,0x2b,
      0x88,0x1d,0xc2,0x00,0xc9,0x83,0x3d,0xa7,
      0x26,0xe9,0x37,0x6c,0x2e,0x32,0xcf,0xf7};
  static const uint8_t x25519_private[32] = {
      0x77,0x07,0x6d,0x0a,0x73,0x18,0xa5,0x7d,
      0x3c,0x16,0xc1,0x72,0x51,0xb2,0x66,0x45,
      0xdf,0x4c,0x2f,0x87,0xeb,0xc0,0x99,0x2a,
      0xb1,0x77,0xfb,0xa5,0x1d,0xb9,0x2c,0x2a};
  static const uint8_t x25519_public[32] = {
      0x85,0x20,0xf0,0x09,0x89,0x30,0xa7,0x54,
      0x74,0x8b,0x7d,0xdc,0xb4,0x3e,0xf7,0x5a,
      0x0d,0xbf,0x3a,0x0d,0x26,0x38,0x1a,0xf4,
      0xeb,0xa4,0xa9,0x8e,0xaa,0x9b,0x4e,0x6a};
  uint8_t digest[32];
  uint8_t hmac[32];
  uint8_t key[20];
  p2p_identity_t identity;

  memset(digest, 0xa5, sizeof(digest));
  p2p_crypto_sha256(NULL, 0, digest);
  if (!bytes_equal(digest, sha256_empty, sizeof(digest))) {
    fputs("empty SHA-256 vector failed\n", stderr);
    return 1;
  }
  p2p_crypto_sha256((const uint8_t *)"abc", 3, digest);
  if (!bytes_equal(digest, sha256_abc, sizeof(digest))) {
    fputs("abc SHA-256 vector failed\n", stderr);
    return 1;
  }

  memset(key, 0x0b, sizeof(key));
  if (p2p_crypto_hmac_sha256(key, sizeof(key),
                             (const uint8_t *)"Hi There", 8, hmac) != P2P_OK ||
      !bytes_equal(hmac, hmac_expected, sizeof(hmac))) {
    fputs("RFC 4231 HMAC-SHA256 vector failed\n", stderr);
    return 1;
  }

  memset(&identity, 0, sizeof(identity));
  if (p2p_crypto_identity_from_secret(&identity, x25519_private) != P2P_OK ||
      !bytes_equal(identity.public_key, x25519_public, sizeof(x25519_public))) {
    fputs("RFC 7748 X25519 public-key vector failed\n", stderr);
    p2p_crypto_wipe(&identity, sizeof(identity));
    return 1;
  }
  p2p_crypto_wipe(&identity, sizeof(identity));
  puts("P2P crypto boundary vectors passed");
  return 0;
}
